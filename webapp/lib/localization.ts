export type TranslationKey = keyof typeof translations;

const localeIndex: Record<Exclude<Locale, 'nl'>, number> = {
  en: 0,
  es: 1,
  fr: 2,
  de: 3,
  it: 4,
  pt: 5,
  zh: 6,
};

export function isLocale(value: unknown): value is Locale {
  return typeof value === 'string' && LOCALES.some((locale) => locale === value);
}

export function translateText(text: string, locale: Locale): string {
  if (locale === 'nl') return text;
  const key = text.trim();
  const translation = Object.hasOwn(translations, key)
    ? translations[key as TranslationKey]
    : undefined;
  if (!translation) return text;
  const translated = translation[localeIndex[locale]];
  const leading = text.match(/^\s*/)?.[0] ?? '';
  const trailing = text.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}
